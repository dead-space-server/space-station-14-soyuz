using Content.Shared.DeadSpace._Soyuz.Botany;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using System.Text;
using System.Linq;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client.DeadSpace._Soyuz.Botany;

[GenerateTypedNameReferences]
public sealed partial class SoyuzPlantAnalyzerWindow : FancyWindow
{
    public Action<bool>? OnAdvancedModeChanged;

    private bool _advanced;

    public SoyuzPlantAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        ModeButton.OnPressed += _ =>
        {
            _advanced = !_advanced;
            ModeButton.Text = Loc.GetString(_advanced
                ? "soyuz-plant-analyzer-advanced-mode"
                : "soyuz-plant-analyzer-basic-mode");
            OnAdvancedModeChanged?.Invoke(_advanced);
        };
    }

    public void Populate(SoyuzPlantAnalyzerReport report)
    {
        _advanced = report.Advanced;
        ModeButton.Text = Loc.GetString(_advanced
            ? "soyuz-plant-analyzer-advanced-mode"
            : "soyuz-plant-analyzer-basic-mode");

        var output = new StringBuilder();
        output.AppendLine(Loc.GetString(report.IsPlant
            ? "soyuz-plant-analyzer-scanned-plant"
            : "soyuz-plant-analyzer-scanned-seed", ("name", Loc.GetString(report.SeedNameKey))));
        output.AppendLine();
        Add(output, "soyuz-plant-analyzer-yield", report.Yield);
        Add(output, "soyuz-plant-analyzer-potency", $"{report.Potency:0.#}%");
        Add(output, "soyuz-plant-analyzer-harvest", Loc.GetString($"soyuz-plant-analyzer-harvest-{report.HarvestType}"));
        Add(output, "soyuz-plant-analyzer-endurance", $"{report.Endurance:0.#}");
        Add(output, "soyuz-plant-analyzer-lifespan", $"{report.Lifespan:0.#}");
        Add(output, "soyuz-plant-analyzer-maturation", $"{report.Maturation:0.#}");
        Add(output, "soyuz-plant-analyzer-production", $"{report.Production:0.#}");
        Add(output, "soyuz-plant-analyzer-growth-stages", report.GrowthStages);
        AddList(output, "soyuz-plant-analyzer-chemistry", report.Chemicals, false);
        AddList(output, "soyuz-plant-analyzer-consumes", report.ConsumedGases, false);
        AddList(output, "soyuz-plant-analyzer-emits", report.EmittedGases, false);
        AddList(output, "soyuz-plant-analyzer-mutations", report.PossibleMutations, false);

        if (report.Advanced)
        {
            output.AppendLine();
            output.AppendLine(Loc.GetString("soyuz-plant-analyzer-advanced-heading"));
            Add(output, "soyuz-plant-analyzer-genetic-instability", report.GeneticInstability.ToString("0.#"));
            Add(output, "soyuz-plant-analyzer-nutrient-usage", report.NutrientConsumption.ToString("0.##"));
            Add(output, "soyuz-plant-analyzer-water-usage", report.WaterConsumption.ToString("0.##"));
            Add(output, "soyuz-plant-analyzer-ideal-heat", report.IdealHeat.ToString("0.#"));
            Add(output, "soyuz-plant-analyzer-heat-tolerance", report.HeatTolerance.ToString("0.#"));
            Add(output, "soyuz-plant-analyzer-toxins", report.ToxinsTolerance.ToString("0.#"));
            Add(output, "soyuz-plant-analyzer-low-pressure", report.LowPressureTolerance.ToString("0.#"));
            Add(output, "soyuz-plant-analyzer-high-pressure", report.HighPressureTolerance.ToString("0.#"));
            Add(output, "soyuz-plant-analyzer-pests", report.PestTolerance.ToString("0.#"));
            Add(output, "soyuz-plant-analyzer-weeds", report.WeedTolerance.ToString("0.#"));
            AddList(output, "soyuz-plant-analyzer-traits", GetTraits(report));
        }

        Report.Text = output.ToString();
    }

    private static void Add(StringBuilder output, string key, object value)
    {
        output.AppendLine(Loc.GetString(key, ("value", value)));
    }

    private static void AddList(StringBuilder output, string key, IEnumerable<string> values, bool translateValues = true)
    {
        var localized = values.Select(value => translateValues ? Loc.GetString(value) : value).ToArray();
        output.AppendLine(Loc.GetString(key, ("value", localized.Length == 0 ? Loc.GetString("soyuz-plant-analyzer-none") : string.Join(", ", localized))));
    }

    private static IEnumerable<string> GetTraits(SoyuzPlantAnalyzerReport report)
    {
        if (report.Seedless)
            yield return "soyuz-plant-analyzer-trait-seedless";
        if (report.Ligneous)
            yield return "soyuz-plant-analyzer-trait-ligneous";
        if (report.CanScream)
            yield return "soyuz-plant-analyzer-trait-screaming";
    }
}
