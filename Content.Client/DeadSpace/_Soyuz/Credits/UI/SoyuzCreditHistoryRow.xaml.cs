using System;
using Content.Shared.DeadSpace._Soyuz.Credits;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Maths;

namespace Content.Client.DeadSpace._Soyuz.Credits.UI;

/// <summary>
/// Строка журнала: сумма, тип, причина, дата. Начисления подсвечены зелёным, траты красным
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SoyuzCreditHistoryRow : PanelContainer
{
    public SoyuzCreditHistoryRow(CreditLogEntryDto entry, bool showTarget, bool showActor)
    {
        RobustXamlLoader.Load(this);

        var positive = entry.Amount > 0;
        var accent = Color.FromHex(positive ? "#6ccf8a" : "#e06c6c");

        Root.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex(positive ? "#17251d" : "#2a1a1d"),
            BorderColor = Color.FromHex(positive ? "#2c4a39" : "#4d2a30"),
            BorderThickness = new Thickness(1),
        };

        AmountLabel.Text = (positive ? "+" : "") + entry.Amount;
        AmountLabel.Modulate = accent;

        TypeLabel.Text = Loc.GetString($"credits-type-{entry.Type}");
        ReasonLabel.Text = entry.Reason;
        ReasonLabel.ToolTip = entry.Reason;
        DateLabel.Text = entry.CreatedAtUtc.ToString("yyyy-MM-dd HH:mm") + " UTC";

        if (showTarget || showActor)
        {
            var parts = new System.Collections.Generic.List<string>();
            if (showTarget)
                parts.Add(Loc.GetString("credits-history-target", ("name", entry.Target)));
            if (showActor)
                parts.Add(Loc.GetString("credits-history-who", ("name", entry.Actor)));

            WhoLabel.Text = string.Join("   ", parts);
            WhoLabel.Visible = true;
        }
    }
}
