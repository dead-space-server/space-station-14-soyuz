using Robust.Shared.Utility;

namespace Content.Client.DeadSpace._Soyuz.Credits.UI;

/// <summary>Карточка товара: название, описание, теги (срок, предмет, профессии), цена и кнопки</summary>
[GenerateTypedNameReferences]
public sealed partial class SoyuzCreditProductCard : PanelContainer
{
    public event Action? BuyPressed;
    public event Action<bool>? EquipPressed;

    private static readonly Color Muted = Color.FromHex("#9aa0b4");
    private static readonly Color Gold = Color.FromHex("#ffd34d");
    private static readonly Color Red = Color.FromHex("#e06c6c");

    public SoyuzCreditProductCard(CreditProductDto p, long balance)
    {
        RobustXamlLoader.Load(this);

        var border = p.Equipped ? Gold : p.Owned ? Color.FromHex("#3f7a56") : Color.FromHex("#383d52");
        Root.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = p.Owned ? Color.FromHex("#1b2420") : Color.FromHex("#1c1f2b"),
            BorderColor = border,
            BorderThickness = new Thickness(p.Equipped ? 2 : 1),
        };

        NameLabel.Text = Loc.GetString(p.Name);

        if (p.Description != null)
        {
            DescLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString(p.Description)));
            DescLabel.Modulate = Muted;
        }
        else
        {
            DescLabel.Visible = false;
        }

        var foreverOwned = p.Owned && p.ExpiresAtUtc == null;
        Tags.AddChild(!foreverOwned && p.DurationDays is { } days
            ? Tag(Loc.GetString("credits-product-duration", ("days", days)), "#5a4a1c")
            : Tag(Loc.GetString("credits-product-permanent"), "#1f4a33"));

        if (p.GivesItem)
            Tags.AddChild(Tag(Loc.GetString("credits-product-gives-item"), "#1f3a5a"));

        if (p.Owned && p.ExpiresAtUtc is { } until)
            Tags.AddChild(Tag(Loc.GetString("credits-product-until", ("date", until.ToString("yyyy-MM-dd HH:mm") + " UTC")), "#1f4a4a"));

        if (p.Equipped)
            Tags.AddChild(Tag(Loc.GetString(p.Permanent ? "credits-tag-always-worn" : "credits-tag-equipped"), "#6b5a14"));
        else if (p.Owned)
            Tags.AddChild(Tag(Loc.GetString("credits-tag-owned"), "#2c3a52"));

        if (p.DiscountPercent > 0)
        {
            var sale = p.SaleUntilUtc is { } saleUntil
                ? Loc.GetString("credits-product-discount-until",
                    ("percent", p.DiscountPercent), ("date", saleUntil.ToString("yyyy-MM-dd HH:mm") + " UTC"))
                : Loc.GetString("credits-product-discount", ("percent", p.DiscountPercent));
            Tags.AddChild(Tag(sale, "#6b1f3a"));
        }

        if (p.StockLeft >= 0)
            Tags.AddChild(Tag(Loc.GetString("credits-product-stock", ("left", p.StockLeft)), p.StockLeft == 0 ? "#5a1f1f" : "#1f3a5a"));

        if (p.AvailableUntilUtc is { } availableUntil)
        {
            Tags.AddChild(Tag(Loc.GetString("credits-product-available-until",
                ("date", availableUntil.ToString("yyyy-MM-dd HH:mm") + " UTC")), "#4a3a1f"));
        }

        if (p.LockReason != "")
            Tags.AddChild(Tag(p.LockReason, "#5a1f1f"));

        if (p.Jobs.Count > 0)
        {
            var protos = IoCManager.Resolve<IPrototypeManager>();
            var names = p.Jobs.Select(j => protos.TryIndex<JobPrototype>(j, out var job) ? job.LocalizedName : j);
            JobsLabel.SetMessage(FormattedMessage.FromUnformatted(
                Loc.GetString("credits-product-jobs", ("jobs", string.Join(", ", names)))));
            JobsLabel.Modulate = Muted;
            JobsLabel.Visible = true;
        }

        PriceLabel.Text = p.DiscountPercent > 0
            ? Loc.GetString("credits-price-discount", ("price", p.Price), ("old", p.OriginalPrice))
            : Loc.GetString("credits-price", ("price", p.Price));
        PriceLabel.Modulate = balance >= p.Price ? Gold : Red;

        var permanentOwned = foreverOwned;
        var soldOut = p.StockLeft == 0;
        BuyButton.Text = permanentOwned
            ? Loc.GetString("credits-shop-owned")
            : p.Owned
                ? Loc.GetString("credits-shop-extend")
                : soldOut
                    ? Loc.GetString("credits-shop-sold-out")
                    : p.LimitReached ? Loc.GetString("credits-shop-limit-reached") : Loc.GetString("credits-shop-buy");
        BuyButton.Disabled = permanentOwned || p.LimitReached || soldOut || p.LockReason != "" || balance < p.Price;
        BuyButton.OnPressed += _ => BuyPressed?.Invoke();

        if (p.Owned && !p.Permanent)
        {
            var equipped = p.Equipped;
            EquipButton.Visible = true;
            EquipButton.Text = equipped ? Loc.GetString("credits-shop-unequip") : Loc.GetString("credits-shop-equip");
            EquipButton.OnPressed += _ => EquipPressed?.Invoke(!equipped);
        }
    }

    private static Control Tag(string text, string background)
    {
        var panel = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex(background) },
        };
        panel.AddChild(new Label { Text = text, Margin = new Thickness(6, 1, 6, 1) });
        return panel;
    }
}
