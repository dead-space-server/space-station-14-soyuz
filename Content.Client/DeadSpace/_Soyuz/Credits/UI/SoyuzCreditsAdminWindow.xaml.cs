using System;
using Content.Shared.DeadSpace._Soyuz.Credits;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Maths;

namespace Content.Client.DeadSpace._Soyuz.Credits.UI;

/// <summary>Окно администратора (флаг Server): поиск игрока, выдача с выбором типа, журнал с фильтрами</summary>
[GenerateTypedNameReferences]
public sealed partial class SoyuzCreditsAdminWindow : DefaultWindow
{
    private const int AnyType = 100;

    private static readonly CreditTransactionType[] GiveTypes =
    {
        CreditTransactionType.AdminGive,
        CreditTransactionType.EventReward,
        CreditTransactionType.ModeratorReward,
        CreditTransactionType.DeveloperReward,
        CreditTransactionType.RolePlayReward,
        CreditTransactionType.OtherReward,
    };

    public event Action<string, int, int, string, string>? OnLookup;
    public event Action<string, long, string, CreditTransactionType>? OnGive;

    private int _page;

    public SoyuzCreditsAdminWindow()
    {
        RobustXamlLoader.Load(this);

        Title = Loc.GetString("credits-admin-title");

        PlayerPanel.PanelOverride = Box("#20243a", "#4a4f68");
        GivePanel.PanelOverride = Box("#1c1f2b", "#383d52");
        LogPanel.PanelOverride = Box("#1c1f2b", "#383d52");
        NoticePanel.PanelOverride = Box("#3a331a", "#6b5a14");
        BalanceLabel.Modulate = Color.FromHex("#ffd34d");

        FilterType.AddItem(Loc.GetString("credits-admin-filter-any-type"), AnyType);
        foreach (var t in Enum.GetValues<CreditTransactionType>())
            FilterType.AddItem(Loc.GetString($"credits-type-{t}"), (int) t);
        FilterType.SelectId(AnyType);
        FilterType.OnItemSelected += a => FilterType.SelectId(a.Id);

        foreach (var t in GiveTypes)
            GiveType.AddItem(Loc.GetString($"credits-type-{t}"), (int) t);
        GiveType.SelectId((int) CreditTransactionType.AdminGive);
        GiveType.OnItemSelected += a => GiveType.SelectId(a.Id);

        LookupButton.OnPressed += _ => Lookup(0);
        PrevButton.OnPressed += _ => Lookup(_page - 1);
        NextButton.OnPressed += _ => Lookup(_page + 1);

        GiveButton.OnPressed += _ =>
        {
            if (!long.TryParse(AmountInput.Text, out var amount))
            {
                ShowNotice(Loc.GetString("credits-admin-notice-invalidamount"));
                return;
            }

            OnGive?.Invoke(TargetInput.Text, amount, ReasonInput.Text, (CreditTransactionType) GiveType.SelectedId);
        };
    }

    private void Lookup(int page)
    {
        _page = Math.Max(0, page);
        var type = FilterType.SelectedId == AnyType ? -1 : FilterType.SelectedId;
        OnLookup?.Invoke(TargetInput.Text, _page, type, FilterActor.Text, FilterReason.Text);
    }

    private void ShowNotice(string text)
    {
        NoticePanel.Visible = !string.IsNullOrEmpty(text);
        NoticeLabel.Text = text;
    }

    public void UpdateState(CreditsAdminState s)
    {
        _page = s.Page;
        ShowNotice(s.Notice);

        BalanceLabel.Text = s.Resolved
            ? Loc.GetString("credits-admin-balance-of", ("name", s.Target), ("amount", s.Balance))
            : "";

        LogTitle.Text = s.Global ? Loc.GetString("credits-admin-global-log") : Loc.GetString("credits-admin-section-log");

        HistoryList.RemoveAllChildren();
        foreach (var e in s.History)
            HistoryList.AddChild(new SoyuzCreditHistoryRow(e, showTarget: s.Global, showActor: true));

        if (s.History.Count == 0 && (s.Resolved || s.Global))
        {
            HistoryList.AddChild(new Label
            {
                Text = Loc.GetString("credits-history-empty"),
                Modulate = Color.FromHex("#9aa0b4"),
            });
        }

        NavRow.Visible = s.Resolved || s.Global;
        PrevButton.Disabled = s.Page <= 0;
        NextButton.Disabled = !s.HasMore;
        PageLabel.Text = Loc.GetString("credits-history-page", ("page", s.Page + 1));
    }

    private static StyleBoxFlat Box(string background, string border) => new()
    {
        BackgroundColor = Color.FromHex(background),
        BorderColor = Color.FromHex(border),
        BorderThickness = new Thickness(1),
    };
}
