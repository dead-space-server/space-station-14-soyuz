namespace Content.Client.DeadSpace._Soyuz.Credits.UI;

/// <summary>Окно игрока: баланс, магазин, история, рефералы</summary>
[GenerateTypedNameReferences]
public sealed partial class SoyuzCreditsWindow : DefaultWindow
{
    public event Action<string>? OnBuy;
    public event Action<string, bool>? OnEquip;
    public event Action<int>? OnPage;
    public event Action<string>? OnApplyReferral;
    public event Action<string>? OnRedeemPromo;

    private static readonly Color Muted = Color.FromHex("#9aa0b4");

    private const int SortPriceAsc = 0;
    private const int SortPriceDesc = 1;
    private const int SortName = 2;
    private const int SortPopular = 3;

    private int _sortId = SortPriceAsc;

    private const int AllCategories = 0;
    private const int Uncategorized = 1000;
    private readonly Dictionary<int, string> _categoryById = new();
    private string? _selectedCategory;
    private CreditsEuiState? _state;

    private int _page;

    public SoyuzCreditsWindow()
    {
        RobustXamlLoader.Load(this);

        Title = Loc.GetString("credits-window-title");

        TabContainer.SetTabTitle(ShopTab, Loc.GetString("credits-tab-shop"));
        TabContainer.SetTabTitle(HistoryTab, Loc.GetString("credits-tab-history"));
        TabContainer.SetTabTitle(ReferralTab, Loc.GetString("credits-tab-referral"));
        TabContainer.SetTabTitle(PromoTab, Loc.GetString("credits-tab-promo"));

        HeaderPanel.PanelOverride = Box("#20243a", "#4a4f68");
        NoticePanel.PanelOverride = Box("#3a331a", "#6b5a14");
        CodePanel.PanelOverride = Box("#1c1f2b", "#383d52");
        ApplyPanel.PanelOverride = Box("#1c1f2b", "#383d52");
        StatsPanel.PanelOverride = Box("#1c1f2b", "#383d52");
        PromoPanel.PanelOverride = Box("#1c1f2b", "#383d52");

        PromoInfo.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("credits-promo-info")));
        PromoInfo.Modulate = Muted;

        SortSelect.AddItem(Loc.GetString("credits-sort-price-asc"), SortPriceAsc);
        SortSelect.AddItem(Loc.GetString("credits-sort-price-desc"), SortPriceDesc);
        SortSelect.AddItem(Loc.GetString("credits-sort-name"), SortName);
        SortSelect.AddItem(Loc.GetString("credits-sort-popular"), SortPopular);
        SortSelect.SelectId(SortPriceAsc);
        SortSelect.OnItemSelected += a =>
        {
            SortSelect.SelectId(a.Id);
            _sortId = a.Id;
            RebuildShop();
        };

        SearchInput.OnTextChanged += _ => RebuildShop();
        CategoryFilter.OnItemSelected += a =>
        {
            CategoryFilter.SelectId(a.Id);
            _selectedCategory = a.Id == AllCategories
                ? null
                : a.Id == Uncategorized ? "" : _categoryById.GetValueOrDefault(a.Id);
            RebuildShop();
        };

        BalanceLabel.Modulate = Color.FromHex("#ffd34d");
        PrevButton.OnPressed += _ => OnPage?.Invoke(_page - 1);
        NextButton.OnPressed += _ => OnPage?.Invoke(_page + 1);

        ApplyButton.OnPressed += _ =>
        {
            if (!string.IsNullOrWhiteSpace(RefInput.Text))
                OnApplyReferral?.Invoke(RefInput.Text);
            RefInput.Text = "";
        };

        PromoButton.OnPressed += _ =>
        {
            if (!string.IsNullOrWhiteSpace(PromoInput.Text))
                OnRedeemPromo?.Invoke(PromoInput.Text);
            PromoInput.Text = "";
        };
    }

    public void UpdateState(CreditsEuiState s)
    {
        _page = s.Page;

        BalanceLabel.Text = Loc.GetString("credits-balance", ("amount", s.Balance));
        PlaytimeLabel.Text = Loc.GetString("credits-playtime", ("hours", s.PlaytimeHours));

        NoticePanel.Visible = !string.IsNullOrEmpty(s.Notice);
        NoticeLabel.Text = s.Notice;

        UpdateShop(s);
        UpdateHistory(s);
        UpdateReferral(s);
    }

    private void UpdateShop(CreditsEuiState s)
    {
        _state = s;
        UpdateCategories(s);
        RebuildShop();
    }

    private void UpdateCategories(CreditsEuiState s)
    {
        CategoryFilter.Clear();
        _categoryById.Clear();
        CategoryFilter.AddItem(Loc.GetString("credits-shop-category-all"), AllCategories);

        for (var i = 0; i < s.Categories.Count; i++)
        {
            var c = s.Categories[i];
            var id = i + 1;
            _categoryById[id] = c.Id;

            var name = Loc.GetString(c.Name);
            if (c.MaxOwned > 0)
            {
                name = Loc.GetString("credits-shop-category-with-limit",
                    ("name", name), ("owned", c.OwnedCount), ("max", c.MaxOwned));
            }

            CategoryFilter.AddItem(name, id);
        }

        var hasUncategorized = s.Products.Any(p => p.Category == null);
        if (hasUncategorized)
            CategoryFilter.AddItem(Loc.GetString("credits-shop-category-uncategorized"), Uncategorized);

        var selected = AllCategories;
        if (_selectedCategory == "" && hasUncategorized)
        {
            selected = Uncategorized;
        }
        else if (!string.IsNullOrEmpty(_selectedCategory))
        {
            foreach (var (id, category) in _categoryById)
            {
                if (category == _selectedCategory)
                    selected = id;
            }
        }

        if (selected == AllCategories)
            _selectedCategory = null;

        CategoryFilter.SelectId(selected);
    }

    private void RebuildShop()
    {
        ShopList.RemoveAllChildren();

        if (_state == null)
            return;

        if (_state.Products.Count == 0)
        {
            ShopList.AddChild(new Label { Text = Loc.GetString("credits-shop-empty"), Modulate = Muted });
            return;
        }

        var shown = 0;
        foreach (var p in Sorted(_state.Products))
        {
            if (!MatchesFilter(p))
                continue;

            var id = p.Id;
            var card = new SoyuzCreditProductCard(p, _state.Balance);
            card.BuyPressed += () => OnBuy?.Invoke(id);
            card.EquipPressed += equip => OnEquip?.Invoke(id, equip);
            ShopList.AddChild(card);
            shown++;
        }

        if (shown == 0)
            ShopList.AddChild(new Label { Text = Loc.GetString("credits-shop-nothing-found"), Modulate = Muted });
    }

    private IEnumerable<CreditProductDto> Sorted(IEnumerable<CreditProductDto> products) => _sortId switch
    {
        SortPriceDesc => products.OrderByDescending(p => p.Price),
        SortName => products.OrderBy(p => Loc.GetString(p.Name), StringComparer.CurrentCultureIgnoreCase),
        SortPopular => products.OrderByDescending(p => p.Sold).ThenBy(p => p.Price),
        _ => products.OrderBy(p => p.Price),
    };

    private bool MatchesFilter(CreditProductDto p)
    {
        if (_selectedCategory != null && (p.Category ?? "") != _selectedCategory)
            return false;

        var query = SearchInput.Text.Trim();
        return query.Length == 0
               || Loc.GetString(p.Name).Contains(query, StringComparison.CurrentCultureIgnoreCase);
    }

    private void UpdateHistory(CreditsEuiState s)
    {
        HistoryList.RemoveAllChildren();

        if (s.History.Count == 0)
            HistoryList.AddChild(new Label { Text = Loc.GetString("credits-history-empty"), Modulate = Muted });

        foreach (var e in s.History)
            HistoryList.AddChild(new SoyuzCreditHistoryRow(e, showTarget: false, showActor: false));

        PrevButton.Disabled = s.Page <= 0;
        NextButton.Disabled = !s.HasMore;
        PageLabel.Text = Loc.GetString("credits-history-page", ("page", s.Page + 1));
    }

    private void UpdateReferral(CreditsEuiState s)
    {
        CodeInput.Text = s.ReferralCode;

        RefInfo.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("credits-referral-info",
            ("hours", s.ReferralMinHours), ("invitee", s.InviteeReward), ("inviter", s.InviterReward))));
        RefInfo.Modulate = Muted;

        RefStatus.SetMessage(FormattedMessage.FromUnformatted(!s.ReferralApplied
            ? Loc.GetString("credits-referral-status-none")
            : s.ReferralRejected
                ? Loc.GetString("credits-referral-status-rejected")
                : s.ReferralRewarded
                    ? Loc.GetString("credits-referral-status-rewarded")
                    : Loc.GetString("credits-referral-status-pending")));
        RefStatus.Modulate = s.ReferralRejected
            ? Color.FromHex("#e06c6c")
            : s.ReferralRewarded ? Color.FromHex("#6ccf8a") : Muted;

        RefInput.Editable = !s.ReferralApplied;
        ApplyButton.Disabled = s.ReferralApplied;

        StatInvited.Text = s.RefInvited.ToString();
        StatRewarded.Text = s.RefRewarded.ToString();
        StatPending.Text = s.RefPending.ToString();
        StatEarned.Text = s.RefEarned.ToString();
    }

    private static StyleBoxFlat Box(string background, string border) => new()
    {
        BackgroundColor = Color.FromHex(background),
        BorderColor = Color.FromHex(border),
        BorderThickness = new Thickness(1),
    };
}