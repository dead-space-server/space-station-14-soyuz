/// <summary>
/// Окно консоли безопасности станции: боковое меню и панель LOCKDOWN.
/// Разделы записей, камер и учёта экипажа открывают свои интерфейсы на этой же консоли.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LockdownConsoleWindow : FancyWindow
{
    [Dependency] private readonly IEntitySystemManager _systems = default!;

    public event Action<string>? OnStartDepartment;
    public event Action<string>? OnCancelDepartment;
    public event Action? OnConfirmStation;
    public event Action? OnCancelStation;
    public event Action<string>? OnOpenSection;

    private static readonly SpriteSpecifier LockdownIcon =
        new SpriteSpecifier.Rsi(new ResPath("_DeadSpace/_Soyuz/Icons/security_console.rsi"), "lockdown");

    private static readonly Color Accent = Color.FromHex("#4aa3ff");
    private static readonly Color Muted = Color.FromHex("#6f86a3");
    private static readonly Color Good = Color.FromHex("#5bd48a");
    private static readonly Color Warn = Color.FromHex("#f0a030");
    private static readonly Color Bad = Color.FromHex("#e06a6a");
    private static readonly Color CardBorder = Color.FromHex("#24364d");

    private readonly SpriteSystem _sprite;

    private SidebarItem? _lockdownItem;
    private bool _sidebarBuilt;

    private readonly Dictionary<string, DepartmentRow> _departments = new();
    private readonly Dictionary<string, Label> _keys = new();

    public LockdownConsoleWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _sprite = _systems.GetEntitySystem<SpriteSystem>();

        ConfirmStationButton.OnPressed += _ => OnConfirmStation?.Invoke();
        CancelStationButton.OnPressed += _ => OnCancelStation?.Invoke();
    }

    public void UpdateState(LockdownConsoleBoundUserInterfaceState state, bool hasAccess)
    {
        if (!_sidebarBuilt)
            BuildSidebar(state);

        if (_departments.Count == 0)
            BuildDepartments(state);

        if (_keys.Count == 0)
            BuildKeys(state);

        var now = state.CurTime;
        var consoleLocked = state.ConsoleLockedUntil > now;

        // Пункт LOCKDOWN доступен только с имплантом допуска.
        if (_lockdownItem != null)
        {
            _lockdownItem.Button.Disabled = !hasAccess;
            _lockdownItem.Caption.Visible = !hasAccess;
            _lockdownItem.Title.FontColorOverride = hasAccess ? Color.White : Muted;
        }

        NoAccessPanel.Visible = !hasAccess;
        LockdownPanel.Visible = hasAccess;

        if (!state.HasStation)
            SetBadge(Loc.GetString("lockdown-ui-no-station"), Bad);
        else if (consoleLocked)
            SetBadge(Loc.GetString("lockdown-ui-console-locked", ("time", FormatTime(state.ConsoleLockedUntil - now))), Warn);
        else
            SetBadge(Loc.GetString("lockdown-ui-console-ready"), Good);

        var stationBusy = state.Station.Phase != LockdownPhase.None;
        var canStart = state.HasStation && !consoleLocked && !stationBusy;

        foreach (var entry in state.Departments)
        {
            if (!_departments.TryGetValue(entry.Id, out var row))
                continue;

            row.Status.Text = PhaseText(entry, now);
            row.Status.FontColorOverride = PhaseColor(entry.Phase);
            row.Card.PanelOverride = CardStyle(entry.Phase == LockdownPhase.None ? CardBorder : PhaseColor(entry.Phase));
            row.Start.Disabled = !canStart || entry.Phase != LockdownPhase.None;
            row.Cancel.Disabled = entry.Phase == LockdownPhase.None;
        }

        StationStatus.Text = PhaseText(state.Station, now);
        StationStatus.FontColorOverride = PhaseColor(state.Station.Phase);
        StationCard.PanelOverride = CardStyle(state.Station.Phase == LockdownPhase.None ? CardBorder : PhaseColor(state.Station.Phase));

        foreach (var key in state.Keys)
        {
            if (!_keys.TryGetValue(key.Job, out var label))
                continue;

            if (key.Confirmed)
            {
                label.Text = Loc.GetString("lockdown-ui-key-confirmed",
                    ("job", key.JobName),
                    ("time", FormatTime(key.ExpiresAt - now)));
                label.FontColorOverride = Good;
            }
            else
            {
                label.Text = Loc.GetString("lockdown-ui-key-waiting", ("job", key.JobName));
                label.FontColorOverride = Muted;
            }
        }

        ConfirmStationButton.Disabled = !canStart;
        CancelStationButton.Disabled = !stationBusy;
    }

    #region Построение элементов

    private void BuildSidebar(LockdownConsoleBoundUserInterfaceState state)
    {
        _sidebarBuilt = true;

        _lockdownItem = CreateSidebarItem(
            Loc.GetString("lockdown-ui-tab-lockdown"),
            LockdownIcon,
            selected: true);
        SidebarList.AddChild(_lockdownItem.Button);

        if (state.Sections.Count > 0)
        {
            SidebarList.AddChild(new PanelContainer
            {
                MinSize = new Vector2(0, 1),
                Margin = new Thickness(0, 4, 0, 4),
                PanelOverride = new StyleBoxFlat { BackgroundColor = CardBorder },
            });
        }

        foreach (var section in state.Sections)
        {
            var id = section.Id;
            var item = CreateSidebarItem(section.Name, section.Icon, selected: false);
            item.Button.OnPressed += _ => OnOpenSection?.Invoke(id);
            SidebarList.AddChild(item.Button);
        }
    }

    private SidebarItem CreateSidebarItem(string title, SpriteSpecifier? icon, bool selected)
    {
        var button = new ContainerButton
        {
            HorizontalExpand = true,
            MinHeight = 48,
        };
        button.AddStyleClass("ButtonSquare");

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 10,
            Margin = new Thickness(0, 0, 8, 0),
        };

        // Акцентная полоса слева у выбранного пункта.
        row.AddChild(new PanelContainer
        {
            MinSize = new Vector2(3, 0),
            VerticalExpand = true,
            PanelOverride = new StyleBoxFlat { BackgroundColor = selected ? Accent : Color.Transparent },
        });

        var texture = new TextureRect
        {
            MinSize = new Vector2(32, 32),
            Stretch = TextureRect.StretchMode.KeepCentered,
            VerticalAlignment = Control.VAlignment.Center,
        };
        if (icon != null)
            texture.Texture = _sprite.Frame0(icon);
        row.AddChild(texture);

        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            VerticalAlignment = Control.VAlignment.Center,
            HorizontalExpand = true,
        };

        var titleLabel = new Label { Text = title };
        var caption = new Label
        {
            Text = Loc.GetString("lockdown-ui-need-access"),
            FontColorOverride = Bad,
            Visible = false,
        };

        text.AddChild(titleLabel);
        text.AddChild(caption);
        row.AddChild(text);
        button.AddChild(row);

        return new SidebarItem(button, titleLabel, caption);
    }

    private void BuildDepartments(LockdownConsoleBoundUserInterfaceState state)
    {
        foreach (var entry in state.Departments)
        {
            var row = new DepartmentRow(entry.Name);
            var id = entry.Id;

            row.Start.OnPressed += _ => OnStartDepartment?.Invoke(id);
            row.Cancel.OnPressed += _ => OnCancelDepartment?.Invoke(id);

            _departments[id] = row;
            DepartmentList.AddChild(row.Card);
        }
    }

    private void BuildKeys(LockdownConsoleBoundUserInterfaceState state)
    {
        foreach (var key in state.Keys)
        {
            var label = new Label();
            _keys[key.Job] = label;
            KeyList.AddChild(label);
        }
    }

    #endregion

    #region Вспомогательное

    private void SetBadge(string text, Color color)
    {
        StatusLabel.Text = text;
        StatusLabel.FontColorOverride = color;
        StatusBadge.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = color.WithAlpha(0.15f),
            BorderColor = color,
            BorderThickness = new Thickness(1),
        };
    }

    private static StyleBoxFlat CardStyle(Color border)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#121b27"),
            BorderColor = border,
            BorderThickness = new Thickness(1),
        };
    }

    private static Color PhaseColor(LockdownPhase phase)
    {
        return phase switch
        {
            LockdownPhase.Pending => Warn,
            LockdownPhase.Active => Bad,
            _ => Muted,
        };
    }

    private static string PhaseText(LockdownEntry entry, TimeSpan now)
    {
        var left = FormatTime(entry.PhaseEnd - now);

        return entry.Phase switch
        {
            LockdownPhase.Pending => Loc.GetString("lockdown-ui-phase-pending", ("time", left)),
            LockdownPhase.Active => Loc.GetString("lockdown-ui-phase-active", ("time", left)),
            _ => Loc.GetString("lockdown-ui-phase-none"),
        };
    }

    private static string FormatTime(TimeSpan time)
    {
        if (time < TimeSpan.Zero)
            time = TimeSpan.Zero;

        return $"{(int) time.TotalMinutes:00}:{time.Seconds:00}";
    }

    private sealed class SidebarItem
    {
        public readonly ContainerButton Button;
        public readonly Label Title;
        public readonly Label Caption;

        public SidebarItem(ContainerButton button, Label title, Label caption)
        {
            Button = button;
            Title = title;
            Caption = caption;
        }
    }

    private sealed class DepartmentRow
    {
        public readonly PanelContainer Card;
        public readonly Label Status;
        public readonly Button Start;
        public readonly Button Cancel;

        public DepartmentRow(string name)
        {
            Card = new PanelContainer
            {
                HorizontalExpand = true,
                PanelOverride = CardStyle(CardBorder),
            };

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
                Margin = new Thickness(12, 8, 12, 8),
            };

            var info = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalAlignment = Control.VAlignment.Center,
            };

            info.AddChild(new Label { Text = name });
            Status = new Label();
            info.AddChild(Status);

            Start = new Button { Text = Loc.GetString("lockdown-ui-start") };
            Cancel = new Button { Text = Loc.GetString("lockdown-ui-cancel") };

            row.AddChild(info);
            row.AddChild(Start);
            row.AddChild(Cancel);
            Card.AddChild(row);
        }
    }

    #endregion
}