    public RepairOrderWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entitySystemManager.GetEntitySystem<SpriteSystem>();
        ShopCheckoutButton.OnPressed += _ => SubmitShopPurchase();
    }

    public void UpdateState(RepairOrderBoundUserInterfaceState state)
    {
        var showActive = state.Active != null && state.Active.RuntimeId != _state?.Active?.RuntimeId;
        if (_state != null && _state.ShopRewardPoolId != state.ShopRewardPoolId)
            _shopCart.Clear();
        _state = state;
        ActivationLabel.Visible = state.Accepting;
        CompletionLabel.Visible = state.Completing;
        AvailableContainer.RemoveAllChildren();
        ActiveContainer.RemoveAllChildren();
        CompletedContainer.RemoveAllChildren();
        WorklistContainer.RemoveAllChildren();
        _offerControls.Clear();
        _activeControls = null;

        if (state.Available.Count == 0)
        {
            AvailableContainer.AddChild(new Label
            {
                Text = Loc.GetString("repair-orders-none-available"),
                FontColorOverride = Color.Gray,
                Margin = new Thickness(4),
            });
        }
        else
        {
            foreach (var entry in state.Available)
            {
                AvailableContainer.AddChild(CreateOrderCard(entry, true));
            }
        }

        if (state.Active == null)
        {
            ActiveContainer.AddChild(new Label
            {
                Text = Loc.GetString("repair-orders-none-active"),
                FontColorOverride = Color.Gray,
                Margin = new Thickness(4),
            });
        }
        else
        {
            ActiveContainer.AddChild(CreateOrderCard(state.Active, false));
        }

        if (state.Completed == null)
        {
            CompletedContainer.AddChild(new Label
            {
                Text = Loc.GetString("repair-orders-none-completed"),
                FontColorOverride = Color.Gray,
                Margin = new Thickness(4),
            });
        }
        else
        {
            CompletedContainer.AddChild(CreateCompletedCard(state.Completed));
        }

        UpdateWorklist(state);
        UpdateShop();

        UpdateTimers();
        if (showActive)
            OrderTabs.CurrentTab = 1;
    }

    public void ShowShopResult(RepairOrderShopResultMessage result)
    {
        if (result.RequestId != _pendingShopRequestId)
            return;

        _shopPurchasePending = false;
        _pendingShopRequestId = null;
        if (result.Success)
            _shopCart.Clear();

        ShopResultLabel.Text = Loc.GetString(result.Message);
        ShopResultLabel.FontColorOverride = result.Success ? Color.LightGreen : Color.Orange;
        UpdateShop();
    }

    private void UpdateWorklist(RepairOrderBoundUserInterfaceState state)
    {
        if (state.Active == null || !state.Active.BlueprintReady)
        {
            WorklistContainer.AddChild(new Label
            {
                Text = Loc.GetString(state.Active == null
                    ? "repair-orders-none-active"
                    : "repair-orders-blueprint-unavailable"),
                FontColorOverride = Color.Gray,
                Margin = new Thickness(4),
            });
            return;
        }

        if (state.Worklist.Count == 0)
        {
            WorklistContainer.AddChild(new Label
            {
                Text = Loc.GetString("repair-orders-worklist-complete"),
                FontColorOverride = Color.LightGreen,
                Margin = new Thickness(4),
            });
            return;
        }

        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(8, 0, 8, 4),
        };
        header.AddChild(new Label
        {
            Text = Loc.GetString("repair-orders-worklist-target"),
            HorizontalExpand = true,
            FontColorOverride = Color.LightGray,
        });
        header.AddChild(new Label
        {
            Text = Loc.GetString("repair-orders-worklist-count"),
            FontColorOverride = Color.LightGray,
        });
        WorklistContainer.AddChild(header);

        foreach (var entry in state.Worklist)
        {
            var row = new PanelContainer { HorizontalExpand = true, Margin = new Thickness(2) };
            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(8, 4),
                SeparationOverride = 8,
            };
            row.AddChild(content);

            var name = entry.PrototypeId;
            if (entry.Type == RepairTaskType.Tile)
            {
                if (_tileDefinitions.TryGetDefinition(entry.PrototypeId, out var definition) &&
                    definition is ContentTileDefinition tile)
                {
                    name = string.IsNullOrEmpty(tile.Name) ? entry.PrototypeId : Loc.GetString(tile.Name);
                    if (tile.Sprite is { } sprite)
                    {
                        content.AddChild(new TextureRect
                        {
                            MinSize = new Vector2(32, 32),
                            Stretch = TextureRect.StretchMode.KeepAspectCentered,
                            Texture = _sprite.Frame0(new SpriteSpecifier.Texture(sprite)),
                        });
                    }
                }
            }
            else if (_prototype.TryIndex<EntityPrototype>(entry.PrototypeId, out var entity))
            {
                name = entity.Name;
                var icon = new EntityPrototypeView
                {
                    SetSize = new Vector2(32, 32),
                    Stretch = SpriteView.StretchMode.Fit,
                };
                icon.SetPrototype(entity.ID);
                content.AddChild(icon);
            }

            content.AddChild(new Label
            {
                Text = entry.Remove
                    ? Loc.GetString("repair-orders-worklist-remove", ("target", name))
                    : name,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            });
            content.AddChild(new Label
            {
                Text = entry.Count.ToString(),
                VerticalAlignment = VAlignment.Center,
                FontColorOverride = Color.LightGray,
            });
            WorklistContainer.AddChild(row);
        }
    }

    private void UpdateShop()
    {
        if (_state == null)
            return;

        var state = _state;
        ShopPointsLabel.Text = Loc.GetString("repair-orders-shop-points", ("points", state.RepairPoints));
        ShopReputationLabel.Text = Loc.GetString("repair-orders-shop-reputation", ("reputation", state.EngineeringReputation));
        ShopLevelLabel.Text = state.ShopLevel > 0
            ? Loc.GetString("repair-orders-shop-level", ("level", state.ShopLevel))
            : Loc.GetString("repair-orders-shop-unavailable");
        ShopProgressBar.Visible = state.NextShopLevelThreshold != null;
        if (state.ShopLevel == 0)
        {
            ShopProgressLabel.Text = string.Empty;
        }
        else if (state.NextShopLevelThreshold is { } nextThreshold)
        {
            ShopProgressLabel.Text = Loc.GetString("repair-orders-shop-next-level",
                ("reputation", state.EngineeringReputation), ("required", nextThreshold));
            ShopProgressBar.Value = nextThreshold <= 0
                ? 0f
                : Math.Clamp((float) state.EngineeringReputation / nextThreshold, 0f, 1f);
        }
        else
        {
            ShopProgressLabel.Text = Loc.GetString("repair-orders-shop-max-level");
        }

        ShopCatalogContainer.RemoveAllChildren();
        ShopCartContainer.RemoveAllChildren();
        if (!_prototype.TryIndex<RepairRewardPoolPrototype>(state.ShopRewardPoolId, out var pool))
        {
            ShopCatalogContainer.AddChild(new Label { Text = Loc.GetString("repair-orders-shop-unavailable") });
            ShopCheckoutButton.Disabled = true;
            return;
        }

        var visibleRewards = new HashSet<string>();
        foreach (var rewardId in pool.Rewards)
        {
            if (!_prototype.TryIndex<RepairRewardPrototype>(rewardId, out var reward) ||
                !_prototype.TryIndex<EntityPrototype>(reward.Entity, out var entity))
                continue;

            var id = rewardId.Id;
            visibleRewards.Add(id);
            _shopCart.TryGetValue(id, out var count);
            var locked = state.ShopLevel < reward.MinimumShopLevel;
            var classified = reward.Classified && locked;
            var row = new PanelContainer { HorizontalExpand = true, Margin = new Thickness(2) };
            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(6, 4),
                SeparationOverride = 6,
            };
            row.AddChild(content);

            if (classified)
            {
                content.AddChild(new Label
                {
                    Text = Loc.GetString("repair-orders-shop-classified-icon"),
                    MinSize = new Vector2(32, 32),
                    HorizontalAlignment = HAlignment.Center,
                    VerticalAlignment = VAlignment.Center,
                    FontColorOverride = Color.Orange,
                });
            }
            else
            {
                var icon = new EntityPrototypeView
                {
                    SetSize = new Vector2(32, 32),
                    Stretch = SpriteView.StretchMode.Fit,
                };
                icon.SetPrototype(entity.ID);
                content.AddChild(icon);
            }

            var details = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
            };
            details.AddChild(new Label
            {
                Text = classified ? Loc.GetString("repair-orders-shop-classified") : entity.Name,
                HorizontalExpand = true,
            });
            details.AddChild(new Label
            {
                Text = classified
                    ? Loc.GetString("repair-orders-shop-classified-details", ("level", reward.MinimumShopLevel))
                    : Loc.GetString("repair-orders-shop-item-details",
                        ("cost", reward.Cost), ("level", reward.MinimumShopLevel)),
                FontColorOverride = locked ? Color.Orange : Color.LightGray,
            });
            content.AddChild(details);

            var remove = new Button
            {
                Text = Loc.GetString("repair-orders-shop-remove"),
                Disabled = count == 0 || _shopPurchasePending,
            };
            remove.OnPressed += _ => ChangeShopQuantity(id, -1, reward.MaxCount);
            content.AddChild(remove);
            var quantity = new LineEdit
            {
                Text = count.ToString(),
                MinSize = new Vector2(48, 0),
                VerticalAlignment = VAlignment.Center,
                Editable = !locked && !_shopPurchasePending,
                IsValid = text => string.IsNullOrEmpty(text) ||
                                    (int.TryParse(text, out var value) && value >= 0 && value <= reward.MaxCount),
            };
            content.AddChild(quantity);
            var add = new Button
            {
                Text = Loc.GetString("repair-orders-shop-add"),
                Disabled = locked || count >= reward.MaxCount || _shopPurchasePending,
            };
            add.OnPressed += _ => ChangeShopQuantity(id, 1, reward.MaxCount);
            content.AddChild(add);
            quantity.OnTextChanged += args =>
            {
                var next = int.TryParse(args.Text, out var value) ? value : 0;
                if (next == 0)
                    _shopCart.Remove(id);
                else
                    _shopCart[id] = next;

                remove.Disabled = next == 0 || _shopPurchasePending;
                add.Disabled = locked || next >= reward.MaxCount || _shopPurchasePending;
                ShopResultLabel.Text = string.Empty;
                UpdateShopCart();
            };
            quantity.OnFocusExit += _ => quantity.Text =
                (_shopCart.TryGetValue(id, out var value) ? value : 0).ToString();
            ShopCatalogContainer.AddChild(row);
        }

        foreach (var stale in _shopCart.Keys.Where(id => !visibleRewards.Contains(id)).ToArray())
            _shopCart.Remove(stale);

        UpdateShopCart();
    }

    private void UpdateShopCart()
    {
        if (_state == null || !_prototype.TryIndex<RepairRewardPoolPrototype>(_state.ShopRewardPoolId, out var pool))
            return;

        ShopCartContainer.RemoveAllChildren();
        long total = 0;
        foreach (var rewardId in pool.Rewards)
        {
            if (!_shopCart.TryGetValue(rewardId.Id, out var count) || count <= 0 ||
                !_prototype.TryIndex<RepairRewardPrototype>(rewardId, out var reward) ||
                !_prototype.TryIndex<EntityPrototype>(reward.Entity, out var entity))
                continue;

            // Two int values always multiply within long; guard the running sum explicitly.
            var lineCost = (long) reward.Cost * count;
            total = lineCost > long.MaxValue - total ? long.MaxValue : total + lineCost;

            ShopCartContainer.AddChild(new Label
            {
                Text = Loc.GetString("repair-orders-shop-cart-line",
                    ("name", entity.Name), ("count", count), ("cost", lineCost)),
            });
        }

        if (_shopCart.Count == 0)
            ShopCartContainer.AddChild(new Label { Text = Loc.GetString("repair-orders-shop-cart-empty") });

        ShopTotalLabel.Text = Loc.GetString("repair-orders-shop-total", ("total", total));
        ShopCheckoutButton.Disabled = _shopCart.Count == 0 || _shopPurchasePending ||
                                      _state.ShopPurchaseInProgress || total > _state.RepairPoints;
    }

    private void ChangeShopQuantity(string id, int delta, int maxCount)
    {
        _shopCart.TryGetValue(id, out var current);
        var next = Math.Clamp(current + delta, 0, maxCount);
        if (next == 0)
            _shopCart.Remove(id);
        else
            _shopCart[id] = next;

        ShopResultLabel.Text = string.Empty;
        UpdateShop();
    }

    private void SubmitShopPurchase()
    {
        if (_shopPurchasePending || _shopCart.Count == 0)
            return;

        _shopPurchasePending = true;
        _pendingShopRequestId = Guid.NewGuid().ToString("N");
        ShopResultLabel.Text = Loc.GetString("repair-orders-shop-processing");
        OnShopPurchase?.Invoke(_pendingShopRequestId, _shopCart
            .Select(line => new RepairOrderRewardBuiEntry(line.Key, line.Value))
            .ToList());
        UpdateShop();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTimers();
    }

    private Control CreateOrderCard(RepairOrderBuiEntry entry, bool available)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(2),
        };

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(8),
            SeparationOverride = 4,
        };
        panel.AddChild(content);

        var title = entry.PrototypeId;
        var description = Loc.GetString("repair-orders-missing-prototype", ("prototype", entry.PrototypeId));
        if (_prototype.TryIndex<RepairOrderPrototype>(entry.PrototypeId, out var order))
        {
            title = Loc.GetString(order.Name);
            description = Loc.GetString(order.Description);
        }

        content.AddChild(new Label
        {
            Text = title,
            StyleClasses = { "LabelHeading" },
            HorizontalExpand = true,
        });

        if (order != null)
        {
            content.AddChild(new Label
            {
                Text = Loc.GetString("repair-orders-object", ("type", Loc.GetString(order.ObjectType)),
                    ("name", Loc.GetString(order.ObjectName))),
            });
        }
        if (!available)
        {
            AddDamageSummary(content, entry.DamageEvents);
            AddExclusions(content, entry.Exclusions);
        }

        var descriptionLabel = new RichTextLabel { HorizontalExpand = true };
        descriptionLabel.SetMarkup(description);
        content.AddChild(descriptionLabel);

        if (order != null)
            AddDifficulty(content, order.Difficulty);

        if (!available)
        {
            content.AddChild(new Label
            {
                Text = Loc.GetString("repair-orders-status-active"),
                FontColorOverride = Color.LightGreen,
            });

            if (entry.ExpiresAt is { } activeExpiresAt)
            {
                var remainingLabel = new Label
                {
                    FontColorOverride = Color.LightGray,
                };
                content.AddChild(remainingLabel);

                // The button is assigned below after all other active-order fields are built.
                _activeControls = (activeExpiresAt, remainingLabel, null!);
            }

            var fraction = entry.BlueprintReady
                ? RepairOrderProgress.CalculateFraction(entry.CompletedTasks, entry.TotalTasks)
                : 0f;
            var percent = RepairOrderProgress.CalculatePercent(entry.CompletedTasks, entry.TotalTasks);

            content.AddChild(new Label
            {
                Text = Loc.GetString(
                    "repair-orders-progress-tasks",
                    ("completed", entry.CompletedTasks),
                    ("total", entry.TotalTasks)),
                FontColorOverride = Color.LightGray,
            });

            content.AddChild(new ProgressBar
            {
                MinValue = 0f,
                MaxValue = 1f,
                Value = fraction,
                HorizontalExpand = true,
                MinHeight = 20f,
            });

            content.AddChild(new Label
            {
                Text = entry.BlueprintReady
                    ? Loc.GetString("repair-orders-progress-percent", ("percent", percent))
                    : Loc.GetString("repair-orders-blueprint-unavailable"),
                FontColorOverride = entry.BlueprintReady ? Color.LightGray : Color.Orange,
                HorizontalAlignment = HAlignment.Right,
            });

            content.AddChild(new Label
            {
                Text = Loc.GetString(
                    "repair-orders-points",
                    ("current", entry.CurrentPoints),
                    ("max", entry.MaxPoints)),
                FontColorOverride = Color.LightGray,
            });

            var actions = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 8,
            };
            content.AddChild(actions);

            var print = new Button
            {
                Text = Loc.GetString("repair-orders-print-report"),
                HorizontalExpand = true,
            };
            print.OnPressed += _ => OnPrintReport?.Invoke(entry.RuntimeId);
            actions.AddChild(print);

            var complete = new Button
            {
                Text = Loc.GetString("repair-orders-submit"),
                HorizontalAlignment = HAlignment.Right,
                HorizontalExpand = true,
                Disabled = !entry.BlueprintReady || _state?.Completing == true,
            };
            complete.OnPressed += _ => OnComplete?.Invoke(entry.RuntimeId);
            actions.AddChild(complete);
            if (_activeControls is { } activeControls)
                _activeControls = (activeControls.ExpiresAt, activeControls.Timer, complete);
            return panel;
        }

        var footer = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };
        content.AddChild(footer);

        var accept = new Button
        {
            Text = Loc.GetString("repair-orders-accept"),
            HorizontalAlignment = HAlignment.Right,
            HorizontalExpand = true,
        };
        accept.OnPressed += _ => OnAccept?.Invoke(entry.RuntimeId);
        footer.AddChild(accept);

        _offerControls[entry.RuntimeId] = accept;
        return panel;
    }

    private static void AddExclusions(BoxContainer content, RepairExclusionTotals totals)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(Loc.GetString("repair-orders-waiver-summary", ("count", totals.Count),
            ("used", totals.WaivedPoints), ("max", totals.MaxWaivedPoints), ("percent", totals.PenaltyPercent),
            ("raw", totals.RawPoints), ("final", totals.FinalPoints)));
        content.AddChild(label);
    }

    private static void AddDifficulty(BoxContainer content, int difficulty)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMarkup(Loc.GetString("repair-orders-difficulty",
            ("class", Loc.GetString(RepairOrderDifficulty.GetName(difficulty))),
            ("difficulty", difficulty), ("max", RepairOrderDifficulty.Maximum)));
        content.AddChild(label);
    }

